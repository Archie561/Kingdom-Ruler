using System;

namespace KingdomRuler.Systems.Ledger
{
    /// <summary>
    /// One warehouse: whole units of a trade resource, its capacity, and how far regeneration has
    /// got toward the next unit. Read-only outside <c>KingdomRuler.Systems</c>; every change goes
    /// through <see cref="KingdomLedger"/>.
    /// </summary>
    /// <remarks>
    /// <para><b>Whole units, no fraction stored.</b> A warehouse gains one unit every
    /// <c>day ÷ capacity</c>, so an empty one is full after exactly 24 hours (GDD §7). Progress
    /// toward the next unit lives in <see cref="LastUpdatedUtc"/>: it is the moment the unit now
    /// regenerating started, and it advances by whole units' worth of time — the same deadline
    /// idea as every timer in the game (<c>ARCHITECTURE.md</c> §4.5). Many short settles and one
    /// long one give the same result, and a save holding the amount and that timestamp holds
    /// everything.</para>
    ///
    /// <para>The arithmetic is exact in <c>long</c> ticks because elapsed time is capped at one
    /// day (a day fills any warehouse) and capacity at <see cref="KingdomLedger.MaxWarehouseCapacity"/>:
    /// <c>TicksPerDay × 10⁷ &lt; long.MaxValue</c>.</para>
    /// </remarks>
    public sealed class TradeResourceState
    {
        private const long TicksPerDay = TimeSpan.TicksPerDay;

        public int Amount   { get; internal set; }
        public int Capacity { get; internal set; }

        /// <summary>When the unit now regenerating started. Equals the last settle whenever no partial unit is pending.</summary>
        public DateTime LastUpdatedUtc { get; internal set; }

        public TradeResourceState(int capacity)
        {
            Capacity       = capacity;
            LastUpdatedUtc = DateTime.UtcNow;
        }

        /// <summary>How long one unit takes to regenerate at this capacity.</summary>
        public TimeSpan TimePerUnit => TimeSpan.FromTicks(TicksPerDay / Capacity);

        /// <summary>Progress toward the next unit at <paramref name="now"/>, 0..1. Zero while full.</summary>
        public float NextUnitProgress(DateTime now)
        {
            if (Amount >= Capacity || now <= LastUpdatedUtc) return 0f;

            long scaled = ElapsedTicks(now) * Capacity;
            return (float)((scaled % TicksPerDay) / (double)TicksPerDay);
        }

        /// <summary>How long until the warehouse is full, from <paramref name="now"/>. Zero when it already is.</summary>
        public TimeSpan TimeUntilFull(DateTime now)
        {
            if (Amount >= Capacity) return TimeSpan.Zero;

            // The k-th missing unit lands once elapsed × capacity ≥ k × day, so round the wait up.
            long missing = Capacity - Amount;
            long needed  = (missing * TicksPerDay + Capacity - 1) / Capacity;
            long elapsed = now > LastUpdatedUtc ? ElapsedTicks(now) : 0L;
            return TimeSpan.FromTicks(Math.Max(0L, needed - elapsed));
        }

        /// <summary>Credit every whole unit regenerated by <paramref name="now"/>, keeping the partial one in <see cref="LastUpdatedUtc"/>.</summary>
        /// <remarks>
        /// A baseline in the future <b>resynchronises</b> to <paramref name="now"/>: nothing else
        /// moves it backwards, so a device clock that ran ahead and was corrected would otherwise
        /// never regenerate again. A full warehouse banks nothing, so the baseline follows the clock.
        /// </remarks>
        internal void AccruePassiveRegen(DateTime now)
        {
            if (now <= LastUpdatedUtc || Amount >= Capacity)
            {
                LastUpdatedUtc = now;
                return;
            }

            long elapsed = (now - LastUpdatedUtc).Ticks;
            if (elapsed >= TicksPerDay)
            {
                Amount         = Capacity;
                LastUpdatedUtc = now;
                return;
            }

            long units = elapsed * Capacity / TicksPerDay;
            if (units == 0) return;

            Amount = (int)Math.Min(Amount + units, Capacity);

            // Floored, so the baseline can only land earlier than the exact unit boundary — by under
            // one tick per unit. Progress is never lost.
            LastUpdatedUtc = Amount >= Capacity
                ? now
                : LastUpdatedUtc.AddTicks(units * TicksPerDay / Capacity);
        }

        private long ElapsedTicks(DateTime now) => Math.Min((now - LastUpdatedUtc).Ticks, TicksPerDay);
    }
}
