using System;
using KingdomRuler.Shared.Accrual;

namespace KingdomRuler.Systems.Ledger
{
    /// <summary>
    /// One warehouse: whole units of a trade resource, its capacity, and how far regeneration has
    /// got toward the next unit. Read-only outside <c>KingdomRuler.Systems</c>; every change goes
    /// through <see cref="KingdomLedger"/>.
    /// </summary>
    /// <remarks>
    /// <para><b>Whole units, no fraction stored.</b> A warehouse gains one unit every
    /// <c>day ÷ capacity</c>, so an empty one is full after exactly 24 hours (GDD §7). Progress
    /// toward the next unit lives in <see cref="LastUpdatedUtc"/>: the moment the unit now
    /// regenerating started. The algorithm is <see cref="WholeUnitAccrual"/>'s, shared with Economy's
    /// business storages so both fill by identical math (<c>ARCHITECTURE.md</c> §4.5); this class
    /// only fixes the period at one day.</para>
    /// </remarks>
    public sealed class TradeResourceState
    {
        /// <summary>An empty warehouse fills in one day at any capacity (GDD §7).</summary>
        private static readonly TimeSpan RegenPeriod = TimeSpan.FromDays(1);

        public int Amount   { get; internal set; }
        public int Capacity { get; internal set; }

        /// <summary>When the unit now regenerating started. Equals the last settle whenever no partial unit is pending.</summary>
        public DateTime LastUpdatedUtc { get; internal set; }

        public TradeResourceState(int capacity)
        {
            Capacity       = capacity;
            LastUpdatedUtc = DateTime.UtcNow;
        }

        /// <summary>How long one unit takes to regenerate at this capacity.</summary>
        public TimeSpan TimePerUnit => WholeUnitAccrual.TimePerUnit(Capacity, RegenPeriod);

        /// <summary>Progress toward the next unit at <paramref name="now"/>, 0..1. Zero while full.</summary>
        public float NextUnitProgress(DateTime now) =>
            WholeUnitAccrual.NextUnitProgress(Amount, Capacity, LastUpdatedUtc, RegenPeriod, now);

        /// <summary>How long until the warehouse is full, from <paramref name="now"/>. Zero when it already is.</summary>
        public TimeSpan TimeUntilFull(DateTime now) =>
            WholeUnitAccrual.TimeUntilFull(Amount, Capacity, LastUpdatedUtc, RegenPeriod, now);

        /// <summary>Credit every whole unit regenerated by <paramref name="now"/>, keeping the partial one in <see cref="LastUpdatedUtc"/>.</summary>
        /// <remarks>A baseline in the future resynchronises to <paramref name="now"/> (<see cref="WholeUnitAccrual.Settle"/>).</remarks>
        internal void AccruePassiveRegen(DateTime now)
        {
            // Amount never exceeds Capacity, an int, so the settled amount fits one.
            Amount = (int)WholeUnitAccrual.Settle(Amount, Capacity, LastUpdatedUtc, RegenPeriod, now, out var startedUtc);
            LastUpdatedUtc = startedUtc;
        }
    }
}
